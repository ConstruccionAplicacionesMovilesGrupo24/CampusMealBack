import {
  Check,
  Column,
  CreateDateColumn,
  Entity,
  Index,
  JoinColumn,
  ManyToOne,
  PrimaryGeneratedColumn,
} from 'typeorm';
import { User } from '../../users/entities/user.entity';
import { ClientPlatform } from '../enums/client-platform.enum';
import { ComparisonLoadOutcome } from '../enums/comparison-load-outcome.enum';
import { PerformanceEventType } from '../enums/performance-event-type.enum';
import { PerformanceScreen } from '../enums/performance-screen.enum';

/**
 * One technical telemetry record (BQ1). Holds no tokens, coordinates, stack traces or exception
 * messages. The owner comes from the access token, never from the body.
 *
 * Three unique indexes keep replays from inflating counts: one per client event, one per
 * session and record type (a session starts once and crashes fatally at most once), and one per
 * load (the first terminal outcome wins).
 */
@Entity({ name: 'performance_events' })
@Index('UQ_performance_events_user_client_event', ['userId', 'clientEventId'], {
  unique: true,
})
@Index(
  'UQ_performance_events_user_session_type',
  ['userId', 'sessionId', 'eventType'],
  { unique: true, where: `"event_type" IN ('SESSION_START', 'FATAL_CRASH')` },
)
@Index('UQ_performance_events_user_load', ['userId', 'loadId'], {
  unique: true,
  where: `"event_type" = 'COMPARISON_LOAD'`,
})
@Index('IDX_performance_events_type_occurred_at', ['eventType', 'occurredAt'])
@Check(
  'CHK_performance_events_type',
  `"event_type" IN ('SESSION_START', 'FATAL_CRASH', 'COMPARISON_LOAD')`,
)
@Check(
  'CHK_performance_events_shape',
  `("event_type" = 'SESSION_START' AND "session_id" IS NOT NULL AND "load_id" IS NULL AND "exception_class" IS NULL AND "duration_ms" IS NULL AND "outcome" IS NULL AND NOT "injected")
   OR ("event_type" = 'FATAL_CRASH' AND "session_id" IS NOT NULL AND "load_id" IS NULL AND "duration_ms" IS NULL AND "outcome" IS NULL)
   OR ("event_type" = 'COMPARISON_LOAD' AND "load_id" IS NOT NULL AND "outcome" IS NOT NULL AND "exception_class" IS NULL AND NOT "injected")`,
)
@Check(
  'CHK_performance_events_duration',
  `"duration_ms" IS NULL OR "duration_ms" BETWEEN 0 AND 600000`,
)
export class PerformanceEvent {
  @PrimaryGeneratedColumn('uuid', {
    primaryKeyConstraintName: 'PK_performance_events_id',
  })
  id: string;

  /** Generated by the client; makes retries idempotent per account. */
  @Column({ name: 'client_event_id', type: 'uuid' })
  clientEventId: string;

  @Column({ name: 'user_id', type: 'uuid' })
  userId: string;

  @ManyToOne(() => User, { nullable: false, onDelete: 'CASCADE' })
  @JoinColumn({
    name: 'user_id',
    foreignKeyConstraintName: 'FK_performance_events_user_id',
  })
  user: User;

  @Column({ name: 'event_type', type: 'varchar', length: 40 })
  eventType: PerformanceEventType;

  /** Required for SESSION_START and FATAL_CRASH; optional for COMPARISON_LOAD. */
  @Column({ name: 'session_id', type: 'uuid', nullable: true })
  sessionId: string | null;

  /** COMPARISON_LOAD only. */
  @Column({ name: 'load_id', type: 'uuid', nullable: true })
  loadId: string | null;

  @Column({ type: 'enum', enum: ClientPlatform, enumName: 'client_platform' })
  platform: ClientPlatform;

  @Column({ name: 'device_model', type: 'varchar', length: 80 })
  deviceModel: string;

  @Column({ name: 'os_version', type: 'varchar', length: 40 })
  osVersion: string;

  @Column({ name: 'app_version', type: 'varchar', length: 40 })
  appVersion: string;

  @Column({ type: 'varchar', length: 40, nullable: true })
  screen: PerformanceScreen | null;

  /** FATAL_CRASH only: class name, never the message or the stack trace. */
  @Column({
    name: 'exception_class',
    type: 'varchar',
    length: 200,
    nullable: true,
  })
  exceptionClass: string | null;

  /** COMPARISON_LOAD: monotonic milliseconds from the request to the rendered content. */
  @Column({ name: 'duration_ms', type: 'integer', nullable: true })
  durationMs: number | null;

  @Column({ type: 'varchar', length: 40, nullable: true })
  outcome: ComparisonLoadOutcome | null;

  /** FATAL_CRASH provoked on purpose by an internal build: its session is never real usage. */
  @Column({ type: 'boolean', default: false })
  injected: boolean;

  /** True for demo data from `npm run seed:bq1`; real clients cannot set it. */
  @Column({ type: 'boolean', default: false })
  synthetic: boolean;

  /** When it happened on the device (UTC). Decides the report window, also for late syncs. */
  @Column({ name: 'occurred_at', type: 'timestamptz' })
  occurredAt: Date;

  /** When the backend stored it. */
  @CreateDateColumn({ name: 'received_at', type: 'timestamptz' })
  receivedAt: Date;
}
