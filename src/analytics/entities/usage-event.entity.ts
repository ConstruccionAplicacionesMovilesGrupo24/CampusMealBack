import {
  Check,
  Column,
  CreateDateColumn,
  Entity,
  Index,
  JoinColumn,
  ManyToOne,
  PrimaryGeneratedColumn,
} from 'typeorm';
import { User } from '../../users/entities/user.entity';
import { BudgetBand } from '../enums/budget-band.enum';
import { ClientPlatform } from '../enums/client-platform.enum';
import { UsageEventType } from '../enums/usage-event-type.enum';
import { UsageFeature } from '../enums/usage-feature.enum';

/**
 * One product-usage event (BQ6). Holds no coordinates, tokens, passwords or free text.
 * The owner comes from the access token, never from the body.
 */
@Entity({ name: 'usage_events' })
@Index('UQ_usage_events_user_client_event', ['userId', 'clientEventId'], {
  unique: true,
})
@Index('IDX_usage_events_occurred_at', ['occurredAt'])
@Index('IDX_usage_events_user_occurred_at', ['userId', 'occurredAt'])
// Declared here too (created by migration 1790520000000) so migration:generate keeps it.
@Check(
  'CHK_usage_events_feature_for_type',
  `("event_type" = 'FEATURE_USED' AND "feature" IS NOT NULL) OR ("event_type" = 'SESSION_STARTED' AND "feature" IS NULL)`,
)
export class UsageEvent {
  @PrimaryGeneratedColumn('uuid', {
    primaryKeyConstraintName: 'PK_usage_events_id',
  })
  id: string;

  /** Generated by the client; makes retries idempotent per account. */
  @Column({ name: 'client_event_id', type: 'uuid' })
  clientEventId: string;

  @Column({ name: 'user_id', type: 'uuid' })
  userId: string;

  @ManyToOne(() => User, { nullable: false, onDelete: 'CASCADE' })
  @JoinColumn({
    name: 'user_id',
    foreignKeyConstraintName: 'FK_usage_events_user_id',
  })
  user: User;

  @Column({
    name: 'event_type',
    type: 'enum',
    enum: UsageEventType,
    enumName: 'usage_event_type',
  })
  eventType: UsageEventType;

  /** Required for FEATURE_USED, null for SESSION_STARTED. */
  @Column({
    type: 'enum',
    enum: UsageFeature,
    enumName: 'usage_feature',
    nullable: true,
  })
  feature: UsageFeature | null;

  @Column({
    type: 'enum',
    enum: ClientPlatform,
    enumName: 'client_platform',
  })
  platform: ClientPlatform;

  /** Optional coarse campus zone (never coordinates). BQ9 demand context. */
  @Column({ name: 'zone_id', type: 'varchar', length: 64, nullable: true })
  zoneId: string | null;

  /** Optional explicit food category the user asked for. BQ9 demand context. */
  @Column({
    name: 'food_category',
    type: 'varchar',
    length: 40,
    nullable: true,
  })
  foodCategory: string | null;

  @Column({
    name: 'budget_band',
    type: 'enum',
    enum: BudgetBand,
    enumName: 'usage_budget_band',
    nullable: true,
  })
  budgetBand: BudgetBand | null;

  /** True for demo data from `npm run seed:usage`; real clients cannot set it. */
  @Column({ type: 'boolean', default: false })
  synthetic: boolean;

  /** When the event happened on the device (UTC). Decides the month BQ6 counts it in. */
  @Column({ name: 'occurred_at', type: 'timestamptz' })
  occurredAt: Date;

  /** When the backend stored it. */
  @CreateDateColumn({ name: 'received_at', type: 'timestamptz' })
  receivedAt: Date;
}
