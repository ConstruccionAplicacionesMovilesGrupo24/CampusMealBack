import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import {
  IsEnum,
  IsISO8601,
  IsOptional,
  IsUUID,
  Matches,
  ValidateIf,
} from 'class-validator';
import { BudgetBand } from '../enums/budget-band.enum';
import { ClientPlatform } from '../enums/client-platform.enum';
import { UsageEventType } from '../enums/usage-event-type.enum';
import { UsageFeature } from '../enums/usage-feature.enum';
import { MealCategory } from '../../restaurants/enums/meal-category.enum';
import { AnalyticsZone } from '../enums/analytics-zone.enum';

/**
 * Body of `POST analytics/usage-events`. No coordinates, tokens or free text: the global
 * whitelist rejects any other field. The user is taken from the access token.
 */
export class CreateUsageEventDto {
  @ApiProperty({
    example: '9b2c7a4e-5d1f-4c8a-8e0b-3a6f1d2c4b55',
    description:
      'UUID generated by the client. Re-sending it (a retry or outbox replay) is accepted but stored once per account.',
  })
  @IsUUID()
  clientEventId: string;

  @ApiProperty({ enum: UsageEventType })
  @IsEnum(UsageEventType)
  eventType: UsageEventType;

  @ApiPropertyOptional({
    enum: UsageFeature,
    nullable: true,
    description:
      'Required for FEATURE_USED; must be null or omitted for SESSION_STARTED.',
  })
  @ValidateIf(
    (dto: CreateUsageEventDto) => dto.eventType === UsageEventType.FEATURE_USED,
  )
  @IsEnum(UsageFeature, {
    message: `feature must be one of ${Object.values(UsageFeature).join(', ')} for FEATURE_USED`,
  })
  feature?: UsageFeature | null;

  @ApiProperty({ enum: ClientPlatform })
  @IsEnum(ClientPlatform)
  platform: ClientPlatform;

  @ApiProperty({
    example: '2026-10-27T15:04:05Z',
    description: 'ISO-8601 UTC instant. A Z suffix is required.',
  })
  @IsISO8601({ strict: true, strictSeparator: true })
  @Matches(/Z$/, {
    message: 'occurredAt must be an ISO-8601 UTC instant ending in Z',
  })
  occurredAt: string;

  @ApiPropertyOptional({
    example: 'campus-001',
    description:
      'Coarse campus zone id (BQ9 demand context). Never coordinates.',
  })
  @IsOptional()
  @IsEnum(AnalyticsZone)
  zoneId?: AnalyticsZone;

  @ApiPropertyOptional({
    example: 'VEGETARIAN',
    description: 'Food category explicitly requested by the user (BQ9).',
  })
  @IsOptional()
  @IsEnum(MealCategory)
  foodCategory?: MealCategory;

  @ApiPropertyOptional({ enum: BudgetBand })
  @IsOptional()
  @IsEnum(BudgetBand)
  budgetBand?: BudgetBand;
}
