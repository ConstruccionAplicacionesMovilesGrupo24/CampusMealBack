import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import {
  IsBoolean,
  IsEnum,
  IsInt,
  IsISO8601,
  IsOptional,
  IsUUID,
  Matches,
  Max,
  MaxLength,
  Min,
  ValidateIf,
} from 'class-validator';
import { ClientPlatform } from '../enums/client-platform.enum';
import {
  ComparisonLoadOutcome,
  OUTCOMES_WITH_CONTENT,
} from '../enums/comparison-load-outcome.enum';
import { PerformanceEventType } from '../enums/performance-event-type.enum';
import { PerformanceScreen } from '../enums/performance-screen.enum';

export const MAX_LOAD_DURATION_MS = 600_000;

/** Printable text without control characters, starting and ending with a visible character. */
const PRINTABLE = /^[^\p{C}\s](?:[^\p{C}]*[^\p{C}\s])?$/u;
/** A JVM class name such as `java.lang.IllegalStateException`: it cannot carry a message. */
const CLASS_NAME = /^[A-Za-z_$][\w$]*(\.[A-Za-z_$][\w$]*)*$/;

const isLoad = (dto: CreatePerformanceEventDto) =>
  dto.eventType === PerformanceEventType.COMPARISON_LOAD;

/**
 * Body of `POST analytics/performance-events`. No tokens, coordinates, stack traces or exception
 * messages: the global whitelist rejects any other field. The user is taken from the token.
 * Fields that do not belong to `eventType` are rejected by the service.
 */
export class CreatePerformanceEventDto {
  @ApiProperty({
    example: '1b9d6bcd-bbfd-4b2d-9b5d-ab8dfbbd4bed',
    description:
      'UUID generated by the client. Re-sending it (a retry or outbox replay) is accepted but stored once per account.',
  })
  @IsUUID()
  clientEventId: string;

  @ApiProperty({ enum: PerformanceEventType })
  @IsEnum(PerformanceEventType)
  eventType: PerformanceEventType;

  @ApiPropertyOptional({
    format: 'uuid',
    description:
      'App session. Required for SESSION_START and FATAL_CRASH, optional for COMPARISON_LOAD. A session counts once per account.',
  })
  @ValidateIf(
    (dto: CreatePerformanceEventDto) => !isLoad(dto) || dto.sessionId != null,
  )
  @IsUUID()
  sessionId?: string | null;

  @ApiPropertyOptional({
    format: 'uuid',
    description:
      'One explicit comparison request. Required for COMPARISON_LOAD, not allowed otherwise. The first terminal outcome is kept.',
  })
  @ValidateIf(
    (dto: CreatePerformanceEventDto) => isLoad(dto) || dto.loadId != null,
  )
  @IsUUID()
  loadId?: string | null;

  @ApiProperty({ example: 'Pixel 8', maxLength: 80 })
  @MaxLength(80)
  @Matches(PRINTABLE, {
    message: 'deviceModel must be non-empty printable text',
  })
  deviceModel: string;

  @ApiProperty({ example: 'Android 16', maxLength: 40 })
  @MaxLength(40)
  @Matches(PRINTABLE, { message: 'osVersion must be non-empty printable text' })
  osVersion: string;

  @ApiProperty({ example: '0.5.0', maxLength: 40 })
  @MaxLength(40)
  @Matches(PRINTABLE, {
    message: 'appVersion must be non-empty printable text',
  })
  appVersion: string;

  @ApiProperty({ enum: ClientPlatform })
  @IsEnum(ClientPlatform)
  platform: ClientPlatform;

  @ApiPropertyOptional({
    enum: PerformanceScreen,
    nullable: true,
    description:
      'COMPARISON_LOAD is always MEAL_COMPARISON. For FATAL_CRASH, the screen on top when known.',
  })
  @IsOptional()
  @IsEnum(PerformanceScreen)
  screen?: PerformanceScreen | null;

  @ApiPropertyOptional({
    example: 'java.lang.IllegalStateException',
    maxLength: 200,
    description:
      'FATAL_CRASH only. Exception class name; messages and stack traces are never accepted.',
  })
  @IsOptional()
  @MaxLength(200)
  @Matches(CLASS_NAME, {
    message: 'exceptionClass must be a class name without a message',
  })
  exceptionClass?: string | null;

  @ApiPropertyOptional({
    example: 1340,
    minimum: 0,
    maximum: MAX_LOAD_DURATION_MS,
    description:
      'COMPARISON_LOAD only. Monotonic milliseconds until the content was rendered. Required when the outcome showed content.',
  })
  @ValidateIf(
    (dto: CreatePerformanceEventDto) =>
      dto.durationMs != null ||
      (isLoad(dto) &&
        dto.outcome != null &&
        OUTCOMES_WITH_CONTENT.includes(dto.outcome)),
  )
  @IsInt()
  @Min(0)
  @Max(MAX_LOAD_DURATION_MS)
  durationMs?: number | null;

  @ApiPropertyOptional({
    enum: ComparisonLoadOutcome,
    description: 'Required for COMPARISON_LOAD, not allowed otherwise.',
  })
  @ValidateIf(
    (dto: CreatePerformanceEventDto) => isLoad(dto) || dto.outcome != null,
  )
  @IsEnum(ComparisonLoadOutcome)
  outcome?: ComparisonLoadOutcome | null;

  @ApiPropertyOptional({
    default: false,
    description:
      'FATAL_CRASH only. True when an internal build provoked the crash on purpose: that whole session is left out of real usage.',
  })
  @IsOptional()
  @IsBoolean()
  injected?: boolean;

  @ApiProperty({
    example: '2026-11-25T17:05:00Z',
    description: 'ISO-8601 UTC instant. A Z suffix is required.',
  })
  @IsISO8601({ strict: true, strictSeparator: true })
  @Matches(/Z$/, {
    message: 'occurredAt must be an ISO-8601 UTC instant ending in Z',
  })
  occurredAt: string;
}
